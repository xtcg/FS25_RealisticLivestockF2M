"""Write tests/fixtures/model_slots_hb15.lua: model slot tables and subtype visual indices of
Hof Bergmann 1.5, FS25_SheepBreedsRLRM and FS25_CowBreedsRLRM, for tests/test_modelmerge.lua.

Only model names (asset file name without folder/extension), slot counts and visual indices are
kept, not the files. Re-run when the map or a pack changes its model tables:

    python tests/gen_model_slots.py <FS25_HofBergmann.zip> <FS25_SheepBreedsRLRM dir> <FS25_CowBreedsRLRM dir>
"""
import hashlib
import os
import subprocess
import sys
import xml.etree.ElementTree as ET
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "fixtures", "model_slots_hb15.lua")
TYPES = ("SHEEP", "COW")


def slots(root):
    names = []
    for animal in root.find("animals").findall("animal"):
        filename = animal.find("assets").get("filename")
        names.append(os.path.splitext(filename.replace("\\", "/").split("/")[-1])[0])
    return names


def visuals(root, type_name):
    """subType name -> [(minAge, visualAnimalIndex)] for the subtypes of `type_name` that carry visuals."""
    out = {}
    for animal in root.iter("animal"):
        if (animal.get("type") or "").upper() != type_name:
            continue
        for sub in animal.findall("subType"):
            name = (sub.get("subType") or sub.get("name") or "").upper()
            pairs = [(int(float(v.get("minAge", 0))), int(v.get("visualAnimalIndex")))
                     for v in sub.iter("visual") if v.get("visualAnimalIndex") is not None]
            if pairs:
                out[name] = pairs
    return out


def config_path(animals_root, type_name):
    for animal in animals_root.iter("animal"):
        if (animal.get("type") or "").upper() == type_name and animal.find("configFilename") is not None:
            return animal.find("configFilename").text.strip()
    return None


def pack_config(pack_root, type_name):
    for override in pack_root.iter("override"):
        if (override.get("type") or "").upper() == type_name:
            return override.get("configFilename")
    return None


def sha(data):
    return hashlib.sha256(data).hexdigest()


def lua_list(items):
    return "{ " + ", ".join(items) + " }"


def lua_table(layer):
    lines = []
    for type_name, data in layer.items():
        lines.append(f"        {type_name} = {{")
        if "slots" in data:
            lines.append("            slots = " + lua_list(f'"{n}"' for n in data["slots"]) + ",")
        lines.append("            subTypes = {")
        for name in sorted(data["subTypes"]):
            pairs = ", ".join(f"{{ {a}, {i} }}" for a, i in data["subTypes"][name])
            lines.append(f"                {name} = {{ {pairs} }},")
        lines.append("            },")
        lines.append("        },")
    return "\n".join(lines)


def git_head(path):
    try:
        return subprocess.check_output(["git", "-C", path, "rev-parse", "--short", "HEAD"], text=True).strip()
    except Exception:
        return "?"


def main(hb_zip, sheep_dir, cow_dir):
    with zipfile.ZipFile(hb_zip) as z:
        hb_animals_bytes = z.read("character/animals.xml")
        hb_animals = ET.fromstring(hb_animals_bytes)
        hb_version = ET.fromstring(z.read("modDesc.xml")).findtext("version")
        hb = {}
        for t in TYPES:
            path = config_path(hb_animals, t)
            hb[t] = {"slots": slots(ET.fromstring(z.read(path))), "subTypes": visuals(hb_animals, t), "config": path}
    with open(hb_zip, "rb") as f:
        hb_sha = sha(f.read())

    rlrm = {t: {"subTypes": visuals(ET.parse(os.path.join(HERE, "..", "xml", "animals.xml")).getroot(), t)} for t in TYPES}

    packs = {}
    for label, directory, type_name in (("SheepBreeds", sheep_dir, "SHEEP"), ("CowBreeds", cow_dir, "COW")):
        root = ET.parse(os.path.join(directory, "animals.xml")).getroot()
        config = pack_config(root, type_name)
        packs[label] = (directory, {type_name: {"slots": slots(ET.parse(os.path.join(directory, config)).getroot()),
                                                 "subTypes": visuals(root, type_name)}})

    out = [
        "-- Model slot tables and subtype visual indices, generated by tests/gen_model_slots.py from:",
        f"--   Hof Bergmann {hb_version} (FS25_HofBergmann.zip sha256 {hb_sha}): character/animals.xml,",
        "--     " + ", ".join(hb[t]["config"] for t in TYPES),
    ]
    for label, (directory, _) in packs.items():
        out.append(f"--   FS25_{label}RLRM {git_head(directory)}: animals.xml + its configOverride table")
    out += [
        "--   RLRM xml/animals.xml (the repo's own subtypes)",
        "-- slots[i] = model of slot i (asset file name); subTypes[name] = { { minAge, visualAnimalIndex }, ... }.",
        "",
        "MODEL_SLOTS = {",
        "    HB = {",
        lua_table({t: {"slots": hb[t]["slots"], "subTypes": hb[t]["subTypes"]} for t in TYPES}),
        "    },",
        "    RLRM = {",
        lua_table(rlrm),
        "    },",
    ]
    for label, (_, layer) in packs.items():
        out += [f"    {label} = {{", lua_table(layer), "    },"]
    out.append("}")
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    print("wrote", OUT)


if __name__ == "__main__":
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    main(*sys.argv[1:])
