loadMod("scripts/market/RLMarketData.lua")
loadMod("scripts/market/RLMarketResourceLock.lua")
local L=RLMarketResourceLock
local locks=L.new()
local a,w=L.resource("ANIMAL","1 22 3"),L.resource("WALLET","7")
check("resources: batch acquisition",locks:acquire("broker:epoch:1",{w,a}))
check("resources: order independent exact retry",locks:acquire("broker:epoch:1",{a,w}))
local ok,reason=locks:acquire("dealer:epoch:2",{L.resource("ANIMAL","1 23 3"),w})
check("resources: whole acquisition refused with no partial lock",not ok and reason=="RESOURCE_BUSY" and locks:owner(L.resource("ANIMAL","1 23 3"))==nil)
ok,reason=locks:acquire("broker:epoch:1",{a})
check("resources: changed retry resource set rejected",not ok and reason=="LOCK_REQUEST_MISMATCH")
locks:markUnknown("broker:epoch:1")
check("resources: unknown exact retry cannot reexecute",not locks:acquire("broker:epoch:1",{a,w}))
check("resources: unknown does not expire or release",not locks:release("broker:epoch:1") and locks:owner(a)=="broker:epoch:1")
local restored=L.new()
check("resources: recover held evidence",restored:restore(locks:snapshot()) and not restored:release("broker:epoch:1"))
check("resources: explicit reconciliation can release",restored:release("broker:epoch:1",true) and restored:owner(a)==nil)
local fresh=L.new();fresh:acquire("tx",{a})
local other=L.new();other:restore(fresh:snapshot())
check("resources: ordinary holds recover as unknown",not other:release("tx"))
check("resources: unsupported kind and sparse list rejected",L.resource("DISPLAY_TAG","22")==nil and not locks:acquire("bad",{[2]=a}))
local safe,accepted=pcall(function() return L.new():restore(3) end)
check("resources: malformed scalar recovery rejected without exception",safe and not accepted)
